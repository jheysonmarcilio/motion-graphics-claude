export function camAt(T) {
	let i = 0; while (i < KEYS.length - 1 && KEYS[i + 1][0] <= T) i++;
	const A = KEYS[i], B = KEYS[i + 1];
	let x = A[2], y = A[3], z = A[4];
	if (B && T > B[0] - B[1]) {
		const k = B[1] <= 0 ? 1 : ease.expoInOut(seg(T, B[0] - B[1], B[0]));
		x = lerp(A[2], B[2], k); y = lerp(A[3], B[3], k); z = lerp(A[4], B[4], k);
	}
	// respiração: deriva lenta proporcional ao zoom
	const d = z / 20;
	x += Math.sin(T * .37) * .05 * d; y += Math.sin(T * .29 + 1) * .05 * d; z *= 1 - .006 * Math.sin(T * .21);
	return { x, y, z, rot: Math.sin(T * .23) * .006 };
}
